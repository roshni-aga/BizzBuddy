import dotenv from "dotenv";
dotenv.config();

import nodemailer from "nodemailer";

const transporter = nodemailer.createTransport({
  service: "gmail",
  auth: {
    user: process.env.EMAIL_USER,
    pass: process.env.EMAIL_PASS,
  },
});

export async function sendRiskEmail(userEmail, summary) {
  try {
    console.log("EMAIL_USER =", process.env.EMAIL_USER);
    console.log("EMAIL_PASS =", process.env.EMAIL_PASS);

    const mailOptions = {
      from: process.env.EMAIL_USER,
      to: userEmail,
      subject: "BizBuddy Risk Alert",
      html: `
        <h2>BizBuddy Risk Summary</h2>

        <p><b>Risk Score:</b> ${summary.riskScore}</p>
        <p><b>Pending Payments:</b> ₹${summary.pendingPayments}</p>
        <p><b>Active Staff:</b> ${summary.activeStaff}/${summary.totalStaff}</p>

        <h3>Alerts</h3>
        <ul>
          ${summary.alerts.map((a) => `<li>${a.message}</li>`).join("")}
        </ul>

        <p style="color:gray">
          This email was automatically generated by BizBuddy.
        </p>
      `,
    };

    await transporter.sendMail(mailOptions);

    console.log("Risk email sent");
  } catch (err) {
    console.error("Email failed:", err.message);
  }
}
